"""
Declaration of the attributes an entity exposes.

Each entity description lists its attributes once (key, and whether the recorder keeps it in history).
Three things derive from that declaration instead of keeping their own tables:

- the translated attribute names (`state_attributes`, generated by `scripts/i18n/generate-attribute-translations`),
- the attributes excluded from the recorder (per entity, see `TibberPricesEntity._apply_recorder_exclusions`),
- the check that an entity only exposes what it declares (`report_undeclared`).

Sensors and binary sensors declare theirs. Numbers and switches only expose `description` (a common attribute) and
the capability attributes Home Assistant adds itself (`min`, `max`, `step`, `mode`), which their small hand-written
exclusion sets cover.
"""

from __future__ import annotations

from dataclasses import dataclass
import logging
from typing import TYPE_CHECKING, Any

if TYPE_CHECKING:
    from collections.abc import Iterable

_LOGGER = logging.getLogger(__name__)

# Tests switch this on: an undeclared attribute then raises instead of being logged once
STRICT = False

_REPORTED: set[tuple[str, str]] = set()


@dataclass(frozen=True, slots=True)
class TibberPricesAttribute:
    """
    One attribute of an entity.

    `name` is the key of its translated name in `scripts/i18n/attribute-names.json`; a `{h}` in it stands for
    an hour count (`trend_{h}h_percent`), filled into `key` (`trend_4h_percent`). `history` keeps the
    attribute in the recorder database; the default leaves it out, so a new attribute can't fill the
    database by accident.
    """

    key: str
    name: str
    history: bool = False
    hours: int | None = None


def attribute(name: str, *, hours: int | None = None, history: bool = False) -> TibberPricesAttribute:
    """Declare an attribute; `hours` fills the `{h}` of a name template."""
    if "{h}" in name:
        if hours is None:
            msg = f"attribute {name!r} needs an hour count"
            raise ValueError(msg)
        return TibberPricesAttribute(name.replace("{h}", str(hours)), name, history, hours)
    if hours is not None:
        msg = f"attribute {name!r} has no {{h}} to fill with an hour count"
        raise ValueError(msg)
    return TibberPricesAttribute(name, name, history)


# Added to every entity by the platform's attribute builder (see sensor/attributes/__init__.py)
COMMON_ATTRIBUTES = (attribute("timestamp"), attribute("description"), attribute("usage_tips"))


def declared_attributes(description: Any) -> tuple[TibberPricesAttribute, ...]:
    """Return the common attributes and those the description declares (entities without any get only the former)."""
    return COMMON_ATTRIBUTES + tuple(getattr(description, "attributes", ()))


def declared_keys(description: Any) -> frozenset[str]:
    """Return the keys of all attributes a description declares, the common ones included."""
    return frozenset(spec.key for spec in declared_attributes(description))


def excluded_keys(description: Any) -> frozenset[str]:
    """Return the keys the recorder leaves out for an entity: every declared attribute not marked `history=True`."""
    return frozenset(spec.key for spec in declared_attributes(description) if not spec.history)


def report_undeclared(description: Any, emitted: Iterable[str], declared: frozenset[str]) -> None:
    """
    Complain about attributes an entity exposes without declaring them.

    Logged once per entity and key; raises in tests (STRICT). `declared` is the entity's `declared_keys()`,
    worked out once by the entity. The chart export's service result is open: it can't be listed.
    """
    if getattr(description, "open_attributes", False):
        return
    missing = sorted(key for key in set(emitted) - declared if (description.key, key) not in _REPORTED)
    if not missing:
        return
    message = f"{description.key} exposes undeclared attributes {missing}: add them to the entity's attributes"
    if STRICT:
        raise AssertionError(message)
    _REPORTED.update((description.key, key) for key in missing)
    _LOGGER.warning(message)
