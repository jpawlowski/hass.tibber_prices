"""
Write and check the index of the decision records.

A decision record is one Markdown file per decision in docs/development/decisions/ (the integration's) or
docs/blueprint/decisions/ (the template's), named and identified ``YYYYMMDD-slug``. Its YAML frontmatter carries
``id``, ``status`` and optionally ``supersedes``, ``superseded-by``, ``rule`` and ``migrated-from``. A rule file named
in ``rule`` ends in a ``Source:`` line naming the record, so the rule an agent follows leads back to why it holds.

Default mode writes ``README.md`` in each decisions folder; ``--check`` only reports, for CI. A repository without a
decisions folder passes — it may still keep the older single DECISIONS.md.

Invoked by script/decisions; not intended to be run directly.
"""

from dataclasses import dataclass, field
from pathlib import Path
import re
import sys

DECISION_DIRS = (Path("docs/development/decisions"), Path("docs/blueprint/decisions"))
INDEX = "README.md"
ID_PATTERN = re.compile(r"^\d{8}-[a-z0-9]+(?:-[a-z0-9]+)*$")
STATUSES = ("accepted", "rejected", "superseded")
LIST_FIELDS = ("supersedes", "superseded-by", "rule")
FIELDS = {"id", "status", "migrated-from", *LIST_FIELDS}

INDEX_HEADER = """# Decision records

Generated by `script/decisions` from the records in this folder — do not edit by hand.

Read this index before a choice that is hard to reverse; read a record only when its decision is the one at hand.
How to write one: the `blueprint-decisions` skill, `references/decision-records.md`.
"""


@dataclass
class Record:
    """One decision record, as parsed from its file."""

    path: Path
    fields: dict[str, object]
    title: str

    @property
    def id(self) -> str:
        """Return the record's id, which is its file name."""
        return self.path.stem

    def links(self, name: str) -> list[str]:
        """Return a field that holds one id or path, or a list of them, as a list."""
        value = self.fields.get(name)
        if isinstance(value, str):
            return [value]
        if isinstance(value, list):
            return [str(item) for item in value]
        return []


@dataclass
class Folder:
    """The records of one decisions folder and the problems found in them."""

    path: Path
    records: dict[str, Record] = field(default_factory=dict)
    errors: list[str] = field(default_factory=list)


def _parse(path: Path, errors: list[str]) -> Record | None:
    import yaml  # noqa: PLC0415  (PyYAML comes with the venv; imported late so --help works without it)

    text = path.read_text(encoding="utf-8")
    parts = text.split("---\n", 2)
    if not text.startswith("---\n") or len(parts) < 3:
        errors.append(f"{path}: no YAML frontmatter between '---' lines")
        return None
    try:
        fields = yaml.safe_load(parts[1]) or {}
    except yaml.YAMLError as err:
        errors.append(f"{path}: frontmatter is not valid YAML: {err}")
        return None
    if not isinstance(fields, dict):
        errors.append(f"{path}: frontmatter is not a mapping")
        return None
    heading = next((line[2:].strip() for line in parts[2].splitlines() if line.startswith("# ")), "")
    if not heading:
        errors.append(f"{path}: no '# ' title in the body")
    return Record(path=path, fields=fields, title=heading)


def _validate(folder: Folder) -> None:
    errors = folder.errors
    for record in folder.records.values():
        where = record.path
        unknown = set(record.fields) - FIELDS
        if unknown:
            errors.append(f"{where}: unknown frontmatter fields {sorted(unknown)}")
        if not ID_PATTERN.match(record.id):
            errors.append(f"{where}: the file name is not YYYYMMDD-slug")
        if record.fields.get("id") != record.id:
            errors.append(f"{where}: id must equal the file name, {record.id}")
        status = record.fields.get("status")
        if status not in STATUSES:
            errors.append(f"{where}: status must be one of {', '.join(STATUSES)}")
        for name in LIST_FIELDS:
            value = record.fields.get(name)
            if value is not None and not (
                isinstance(value, str) or (isinstance(value, list) and all(isinstance(item, str) for item in value))
            ):
                errors.append(f"{where}: {name} must be a string or a list of strings")
        if (status == "superseded") != bool(record.links("superseded-by")):
            errors.append(f"{where}: a superseded record names its successor in superseded-by, and only it does")
        for later in record.links("superseded-by"):
            successor = folder.records.get(later)
            if successor is None:
                errors.append(f"{where}: superseded-by {later} has no record in {folder.path}")
            elif record.id not in successor.links("supersedes"):
                errors.append(f"{where}: {later} does not list {record.id} in supersedes")
        for earlier in record.links("supersedes"):
            predecessor = folder.records.get(earlier)
            if predecessor is None:
                errors.append(f"{where}: supersedes {earlier} has no record in {folder.path}")
            elif record.id not in predecessor.links("superseded-by"):
                errors.append(f"{where}: {earlier} does not list {record.id} in superseded-by")
        for rule in record.links("rule"):
            rule_path = Path(rule)
            if not rule_path.is_file():
                errors.append(f"{where}: rule {rule} does not exist")
            elif f"Source: {record.path.as_posix()}" not in rule_path.read_text(encoding="utf-8"):
                errors.append(f"{where}: rule {rule} has no 'Source: {record.path.as_posix()}' line")


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    """Return a Markdown table padded the way Prettier writes one, so formatting the index changes nothing."""
    widths = [max(len(row[column]) for row in [header, *rows]) for column in range(len(header))]

    def line(cells: list[str]) -> str:
        return "| " + " | ".join(cell.ljust(width) for cell, width in zip(cells, widths, strict=True)) + " |"

    return [line(header), "| " + " | ".join("-" * width for width in widths) + " |", *(line(row) for row in rows)]


def _index(folder: Folder) -> str:
    ordered = sorted(folder.records.values(), key=lambda record: record.id, reverse=True)
    in_force = [record for record in ordered if record.fields.get("status") == "accepted"]
    history = [record for record in ordered if record.fields.get("status") != "accepted"]

    lines = [INDEX_HEADER, "## In force", ""]
    if in_force:
        lines += _table(
            ["Record", "Decision", "Rule"],
            [
                [
                    f"[{record.id}]({record.path.name})",
                    _cell(record.title),
                    ", ".join(f"`{rule}`" for rule in record.links("rule")) or "—",
                ]
                for record in in_force
            ],
        )
    else:
        lines.append("None yet.")
    lines += ["", "## History", ""]
    if history:
        lines += _table(
            ["Record", "Decision", "Status", "Superseded by"],
            [
                [
                    f"[{record.id}]({record.path.name})",
                    _cell(record.title),
                    str(record.fields.get("status")),
                    ", ".join(f"[{item}]({item}.md)" for item in record.links("superseded-by")) or "—",
                ]
                for record in history
            ],
        )
    else:
        lines.append("None yet.")
    return "\n".join(lines) + "\n"


def _load(path: Path) -> Folder:
    folder = Folder(path=path)
    for record_path in sorted(path.glob("*.md")):
        if record_path.name == INDEX:
            continue
        record = _parse(record_path, folder.errors)
        if record is not None:
            folder.records[record.id] = record
    _validate(folder)
    return folder


def main(argv: list[str]) -> int:
    """Write (default) or check (--check) the index of every decisions folder that exists."""
    check = argv == ["--check"]
    if argv and not check:
        print("usage: script/decisions [--check]", file=sys.stderr)
        return 2

    folders = [_load(path) for path in DECISION_DIRS if path.is_dir()]
    if not folders:
        print("No decisions folder — nothing to index")
        return 0

    failed = False
    for folder in folders:
        index_path = folder.path / INDEX
        wanted = _index(folder)
        current = index_path.read_text(encoding="utf-8") if index_path.is_file() else None
        if current != wanted:
            if check:
                folder.errors.append(f"{index_path} is out of date — run script/decisions")
            else:
                index_path.write_text(wanted, encoding="utf-8")
                print(f"Wrote {index_path}")
        for error in folder.errors:
            print(f"✗ {error}", file=sys.stderr)
        failed = failed or bool(folder.errors)
        if not folder.errors:
            print(f"✓ {folder.path}: {len(folder.records)} records")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
